// ============================================================
// src/engine.cpp
//
// Simulation engine of the mechanistic (simulation-based likelihood)
// functional response model (Okuyama 2012, 2026), compiled with Rcpp.
//
// One foraging trial (duration T, H hosts or prey, one consumer):
//   * search time      ~ F_search with mean 1 / lambda,
//                        lambda = a * R^z, where R = H (parasitoid process:
//                        hosts stay in the arena) or R = remaining prey
//                        (predator process: consumed prey are removed);
//   * parasitoid: the host attacked is chosen at random among the H hosts
//                 and the response is the number of DISTINCT hosts attacked;
//     predator:   each encounter consumes one prey; the response is the
//                 number of prey consumed;
//   * handling time    ~ F_handling with mean h and standard deviation s
//                        (natural scale); s = 0 gives a fixed handling time;
//   * the trial ends when the elapsed time exceeds T.
//
// End of the trial: by default an attack counts as soon as the host or prey is
// encountered, even if its handling would end after T (Okuyama 2026: "it was
// assumed that parasitism was successful even if the trial ended while the
// parasitoid was still handling a host"). With exclude_unfinished = true the
// host or prey still being handled at T is not counted: the handling time is
// drawn at the encounter and the attack counts only if handling ends by T.
// The default convention keeps the random-number order of version 1.1.0.
//
// Families (codes used by the R layer, see R/model_spec.R):
//   search:   0 Gamma (shape k), 1 Lognormal, 2 Weibull,
//             9 user R function, 10 user C++ function (external pointer).
//             For the built-in families the dispersion parameter is k,
//             defined by CV^2 = 1 / k of the search time (for the Gamma,
//             k is its shape, as in Okuyama 2026).
//   handling: 0 Lognormal, 1 Gamma, 2 Weibull, 3 constant (= h),
//             9 user R function, 10 user C++ function.
//             For the built-in families the dispersion parameter is s, the
//             standard deviation on the natural scale (same units as h).
//   User functions return variates with MEAN 1 given one shape parameter
//   (k for search, s for handling); the engine multiplies them by the
//   required mean (1 / lambda or h).
//
// The default model (Gamma search, Lognormal handling, parasitoid process)
// consumes random numbers in exactly the same order as version 1.1.0 and as
// the supplementary code of Okuyama (2026); tests/testthat/test-regression.R
// checks this bit by bit.
//
// Saturation cut-off (exact): once all hosts have been attacked (or all prey
// consumed) the response cannot change, so the trial is stopped there.
//
// Random numbers: the exported wrappers generated by Rcpp already open an
// RNGScope, so none is opened here. When a user R function is called, the
// RNG state is written back to R before the call and read again after it,
// so that R code and C++ code share one stream. No seed is set here.
// ============================================================

#include <Rcpp.h>
#include <cmath>
#include <vector>
#include <memory>

using namespace Rcpp;

typedef double (*funres_rng_fun)(double shape);

enum { S_GAMMA = 0, S_LNORM = 1, S_WEIBULL = 2, F_USER_R = 9, F_USER_CPP = 10 };
enum { HD_LNORM = 0, HD_GAMMA = 1, HD_WEIBULL = 2, HD_CONST = 3 };

// Weibull shape b with a given squared coefficient of variation:
// CV^2(b) = Gamma(1 + 2/b) / Gamma(1 + 1/b)^2 - 1, decreasing in b.
static double weibull_shape_from_cv2(double cv2) {
    if (!(cv2 > 0) || !R_finite(cv2)) stop("Weibull: the CV must be finite and > 0");
    auto f = [](double lb) {
        double b = std::exp(lb);
        return std::exp(R::lgammafn(1 + 2 / b) - 2 * R::lgammafn(1 + 1 / b)) - 1;
    };
    double lo = std::log(0.02), hi = std::log(1e4);   // CV from ~1e+18 to ~1e-4
    if (cv2 >= f(lo)) return std::exp(lo);
    if (cv2 <= f(hi)) return std::exp(hi);
    for (int i = 0; i < 200; ++i) {
        double mid = 0.5 * (lo + hi);
        if (f(mid) > cv2) lo = mid; else hi = mid;
        if (hi - lo < 1e-13) break;
    }
    return std::exp(0.5 * (lo + hi));
}

// Draws mean-1 variates from a user R function in blocks, so that R is
// called once per block and not once per event.
class UserRSampler {
public:
    UserRSampler(SEXP fun, double shape, int block = 256)
        : f_(fun), shape_(shape), block_(block), pos_(block) {}
    double next() {
        if (pos_ >= (int) buf_.size()) refill();
        return buf_[pos_++];
    }
private:
    void refill() {
        PutRNGstate();
        NumericVector v = f_(block_, shape_);
        GetRNGstate();
        if (v.size() != block_)
            stop("user sampler must return exactly n values (got %d, expected %d)",
                 (int) v.size(), block_);
        for (int i = 0; i < block_; ++i)
            if (!(v[i] >= 0) || !R_finite(v[i]))
                stop("user sampler returned a value that is not finite and >= 0");
        buf_.assign(v.begin(), v.end());
        pos_ = 0;
    }
    Function f_;
    double shape_;
    int block_;
    int pos_;
    std::vector<double> buf_;
};

static funres_rng_fun get_cpp_fun(SEXP ptr) {
    if (TYPEOF(ptr) != EXTPTRSXP) stop("expected an external pointer to a C++ sampler");
    XPtr<funres_rng_fun> xp(ptr);
    funres_rng_fun f = *xp;
    if (f == NULL) stop("null C++ sampler");
    return f;
}

// ---- Search-time sampler ------------------------------------------------
// Precomputes, for r = 1..H available hosts/prey, the mean search time
// 1 / (a r^z) and the Gamma scale 1 / (k a r^z) (same order of operations as
// version 1.1.0, so the default model reproduces it exactly).
class SearchSampler {
public:
    SearchSampler(int family, int H, double a, double z, double k, SEXP fun)
        : fam_(family), k_(k), mean_(H + 1, 0.0), gscale_(H + 1, 0.0) {
        for (int r = 1; r <= H; ++r) {
            double rate = k * a * R_pow((double) r, z);
            gscale_[r] = 1.0 / rate;
            mean_[r] = 1.0 / (a * R_pow((double) r, z));
        }
        switch (fam_) {
        case S_GAMMA: break;
        case S_LNORM:
            ln_sd_ = std::sqrt(std::log(1 + 1 / k));
            ln_shift_ = -0.5 * ln_sd_ * ln_sd_;   // log-mean of a mean-1 variate
            break;
        case S_WEIBULL:
            wb_shape_ = weibull_shape_from_cv2(1 / k);
            wb_m1scale_ = 1.0 / std::exp(R::lgammafn(1 + 1 / wb_shape_));
            break;
        case F_USER_R:   rs_.reset(new UserRSampler(fun, k)); break;
        case F_USER_CPP: cf_ = get_cpp_fun(fun); break;
        default: stop("unknown search family code %d", fam_);
        }
    }
    // search time when r hosts/prey are available
    double draw(int r) {
        switch (fam_) {
        case S_GAMMA:   return R::rgamma(k_, gscale_[r]);
        case S_LNORM:   return mean_[r] * std::exp(R::rnorm(ln_shift_, ln_sd_));
        case S_WEIBULL: return mean_[r] * wb_m1scale_ * R::rweibull(wb_shape_, 1.0);
        case F_USER_R:  return mean_[r] * rs_->next();
        default: {
            double v = cf_(k_);
            if (!(v >= 0) || !R_finite(v))
                stop("C++ search sampler returned a value that is not finite and >= 0");
            return mean_[r] * v;
        }
        }
    }
private:
    int fam_;
    double k_;
    std::vector<double> mean_, gscale_;
    double ln_sd_ = 0, ln_shift_ = 0, wb_shape_ = 0, wb_m1scale_ = 0;
    std::unique_ptr<UserRSampler> rs_;
    funres_rng_fun cf_ = NULL;
};

// ---- Handling-time sampler (mean h, natural-scale SD s) ------------------
class HandlingSampler {
public:
    HandlingSampler(int family, double h, double s, SEXP fun)
        : fam_(family), h_(h), s_(s) {
        fixed_ = (s == 0) || (family == HD_CONST);
        if (fixed_) return;
        if (!(h > 0)) stop("h must be > 0 when s > 0");
        switch (fam_) {
        case HD_LNORM:
            ln_sd_ = std::sqrt(std::log(1 + (s / h) * (s / h)));
            ln_mu_ = std::log(h) - 0.5 * ln_sd_ * ln_sd_;
            break;
        case HD_GAMMA:
            g_shape_ = (h / s) * (h / s);
            g_scale_ = s * s / h;
            break;
        case HD_WEIBULL:
            w_shape_ = weibull_shape_from_cv2((s / h) * (s / h));
            w_scale_ = h / std::exp(R::lgammafn(1 + 1 / w_shape_));
            break;
        case F_USER_R:   rs_.reset(new UserRSampler(fun, s)); break;
        case F_USER_CPP: cf_ = get_cpp_fun(fun); break;
        default: stop("unknown handling family code %d", fam_);
        }
    }
    double draw() {
        if (fixed_) return h_;
        switch (fam_) {
        case HD_LNORM:   return std::exp(R::rnorm(ln_mu_, ln_sd_));
        case HD_GAMMA:   return R::rgamma(g_shape_, g_scale_);
        case HD_WEIBULL: return R::rweibull(w_shape_, w_scale_);
        case F_USER_R:   return h_ * rs_->next();
        default: {
            double v = cf_(s_);
            if (!(v >= 0) || !R_finite(v))
                stop("C++ handling sampler returned a value that is not finite and >= 0");
            return h_ * v;
        }
        }
    }
private:
    int fam_;
    double h_, s_;
    bool fixed_;
    double ln_mu_ = 0, ln_sd_ = 0, g_shape_ = 0, g_scale_ = 0, w_shape_ = 0, w_scale_ = 0;
    std::unique_ptr<UserRSampler> rs_;
    funres_rng_fun cf_ = NULL;
};

static void check_par(double a, double h, double z, double k, double s, double T) {
    if (!(a > 0) || !(k > 0) || !(h >= 0) || !(s >= 0) || !(T > 0) ||
        !R_finite(a) || !R_finite(k) || !R_finite(h) || !R_finite(s) || !R_finite(z))
        stop("invalid parameters (need finite a > 0, k > 0, h >= 0, s >= 0, T > 0)");
}

// Core engine. Returns, for each of nsim trials, the response (distinct
// hosts attacked or prey consumed). If n_loops is not NULL it accumulates the
// number of encounters (diagnostic) and stops with +Inf at max_loops.
static IntegerVector engine(int H, double a, double h, double z, double k,
                            double s, double T, int nsim,
                            int search_family, int handling_family,
                            bool predator, bool cut,
                            SEXP search_fun, SEXP handling_fun,
                            double* n_loops = NULL, double max_loops = 1e9,
                            bool force_general = false,
                            bool exclude_unfinished = false) {
    if (H < 1) stop("H must be >= 1");
    if (nsim < 1) stop("nsim must be >= 1");
    check_par(a, h, z, k, s, T);

    IntegerVector out(nsim);

    // Fast path for the default model (Gamma search, Lognormal or fixed
    // handling, parasitoid process): the loop of version 1.1.0, with no
    // dispatch per event. Same random numbers, in the same order, as the
    // general loop below.
    if (search_family == S_GAMMA && (handling_family == HD_LNORM || s == 0) &&
        !predator && n_loops == NULL && !force_general && !exclude_unfinished) {
        const double rate = k * a * R_pow((double) H, z);
        const double gscale = 1.0 / rate;
        const bool fixed = (s == 0);
        double lmu = 0.0, lsd = 0.0;
        if (!fixed) {
            if (!(h > 0)) stop("h must be > 0 when s > 0");
            lsd = std::sqrt(std::log(1 + (s / h) * (s / h)));
            lmu = std::log(h) - 0.5 * lsd * lsd;
        }
        std::vector<unsigned char> hit(H);
        for (int sim = 0; sim < nsim; ++sim) {
            std::fill(hit.begin(), hit.end(), 0);
            int count = 0;
            double t = 0.0;
            while (t < T) {
                t += R::rgamma(k, gscale);
                if (t > T) break;
                int pid = (int) std::floor(R::runif(0, H));
                if (!hit[pid]) { hit[pid] = 1; ++count; }
                if (cut && count == H) break;
                t += fixed ? h : std::exp(R::rnorm(lmu, lsd));
            }
            out[sim] = count;
            if (sim % 1000 == 0) Rcpp::checkUserInterrupt();
        }
        return out;
    }

    SearchSampler search(search_family, H, a, z, k, search_fun);
    HandlingSampler handling(handling_family, h, s, handling_fun);

    std::vector<unsigned char> attacked(predator ? 0 : H);
    double loops = 0;

    for (int sim = 0; sim < nsim; ++sim) {
        if (!predator) std::fill(attacked.begin(), attacked.end(), 0);
        int count = 0;
        double t = 0.0;

        while (t < T) {
            t += search.draw(predator ? H - count : H);
            if (t > T) break;

            int pid = predator ? -1 : (int) std::floor(R::runif(0, H));
            if (n_loops != NULL) {
                loops += 1;
                if (loops >= max_loops) { *n_loops = R_PosInf; return out; }
            }
            if (exclude_unfinished) {
                // the attack counts only if its handling ends by T; otherwise
                // the trial ends with this host or prey still being handled
                t += handling.draw();
                if (t > T) break;
            }
            if (predator) {
                ++count;
            } else if (!attacked[pid]) {
                attacked[pid] = 1; ++count;
            }
            if ((predator || cut) && count == H) break;

            if (!exclude_unfinished) t += handling.draw();
        }

        out[sim] = count;
        if (sim % 1000 == 0) Rcpp::checkUserInterrupt();
    }
    if (n_loops != NULL) *n_loops = loops;
    return out;
}

// Direct draws of search times (mean `mean`) or handling times (mean `mean`,
// SD `disp`) with the same code as the engine; used by the tests to check
// the mean and the dispersion of every family, and by test_sampler().
// [[Rcpp::export]]
NumericVector draw_times_cpp(int n, bool search, int family, double mean,
                             double disp, SEXP fun = R_NilValue) {
    NumericVector out(n);
    if (!(mean > 0) || !(disp >= 0)) stop("need mean > 0 and disp >= 0");
    if (search) {
        if (!(disp > 0)) stop("the search dispersion k must be > 0");
        SearchSampler smp(family, 1, 1.0 / mean, 1.0, disp, fun);
        for (int i = 0; i < n; ++i) out[i] = smp.draw(1);
    } else {
        HandlingSampler smp(family, mean, disp, fun);
        for (int i = 0; i < n; ++i) out[i] = smp.draw();
    }
    return out;
}

// General engine (used by the R layer).
// [[Rcpp::export]]
IntegerVector sim_trials_cpp(int H, double a, double h, double z, double k,
                             double s, double T, int nsim,
                             int search_family = 0, int handling_family = 0,
                             bool predator = false, bool cut = true,
                             SEXP search_fun = R_NilValue,
                             SEXP handling_fun = R_NilValue,
                             bool force_general = false,
                             bool exclude_unfinished = false) {
    return engine(H, a, h, z, k, s, T, nsim, search_family, handling_family,
                  predator, cut, search_fun, handling_fun, NULL, 1e9,
                  force_general, exclude_unfinished);
}

// Engine of version 1.1.0 (Gamma search, Lognormal handling, parasitoid),
// kept with its original signature: the regression tests call it.
// [[Rcpp::export]]
IntegerVector sim_engine_cpp(int H, double a, double h, double z,
                                double k, double s, double T,
                                int nsim, bool stop_saturated = true) {
    return engine(H, a, h, z, k, s, T, nsim, S_GAMMA, HD_LNORM, false,
                  stop_saturated, R_NilValue, R_NilValue);
}

// Total number of encounters over nsim trials (diagnostic used by the tests
// to show that the saturation cut-off removes the computational trap
// h ~ 0, k ~ 0). Returns Inf if max_loops is hit.
// [[Rcpp::export]]
double count_loops_cpp(int H, double a, double h, double z,
                          double k, double s, double T, int nsim,
                          bool stop_saturated, double max_loops = 1e9) {
    double loops = 0;
    engine(H, a, h, z, k, s, T, nsim, S_GAMMA, HD_LNORM, false,
           stop_saturated, R_NilValue, R_NilValue, &loops, max_loops);
    return loops;
}

// Example C++ sampler for the documentation and the tests: mean-1 Gamma
// variate with shape `shape` (identical in law to the built-in Gamma search).
static double example_gamma_mean1(double shape) {
    return R::rgamma(shape, 1.0 / shape);
}

// [[Rcpp::export]]
SEXP example_cpp_sampler() {
    XPtr<funres_rng_fun> p(new funres_rng_fun(&example_gamma_mean1), true);
    return p;
}
